/** Every silhouette the generator can build a level inside. */
export const SHAPE_ART: readonly ShapeArt[] = [
  ...symbols,
  ...objects,
  ...nature,
  ...food,
  ...technology,
  ...seasonal,
  ...abstract,
];

/** Look one up by id. */
export function shapeArtById(id: string): ShapeArt | undefined {
  return SHAPE_ART.find((shape) => shape.id === id);
}

/** All ids, for the generator to pick from. */
export const SHAPE_ART_IDS: readonly string[] = SHAPE_ART.map((s) => s.id);
