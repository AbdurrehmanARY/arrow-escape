/**
 * shapeArt.ts — the silhouette library.
 *
 * Purpose:      Every recognisable outline a level can be built inside.
 * Responsibilities:
 *               - One bitmap per shape, plus its name and category.
 * Notes:        Bitmaps rather than maths. A circle or a diamond is a tidy
 *               inequality, but there is no formula for "guitar" or "owl" — and
 *               the moment the shape library has to cover objects and animals,
 *               implicit surfaces stop being the right tool. These are sampled
 *               and scaled to whatever board size a level needs, so one 16x16
 *               drawing serves a 9x9 board and a 24x24 one.
 *
 *               Drawn at 16x16 on purpose. Big enough for a readable silhouette,
 *               small enough that every shape is legible when a level shrinks it,
 *               and uniform so a new one can be checked against the others at a
 *               glance. `#` is inside the shape; everything else is outside.
 *
 *               Silhouettes are chosen for *outline clarity*, not detail. Snakes
 *               fill the mask and blur fine features, so a bold shape reads and a
 *               fussy one turns to mush.
 *
 *               Adding a shape is adding an entry here. Nothing else changes.
 */

export type ShapeCategory =
  'symbol' | 'object' | 'nature' | 'food' | 'technology' | 'seasonal' | 'abstract';

export interface ShapeArt {
  readonly id: string;
  readonly name: string;
  readonly category: ShapeCategory;
  /** 16 rows of 16 characters. `#` is inside the shape. */
  readonly art: readonly string[];
}

const art = (
  id: string,
  name: string,
  category: ShapeCategory,
  rows: readonly string[],
): ShapeArt => ({ id, name, category, art: rows });

