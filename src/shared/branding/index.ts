/**
 * shared/branding/index.ts — the game's name and its approved artwork.
 *
 * Purpose:      One place that knows what this game is called and which files are
 *               its logo, so no screen hard-codes a string or reaches into
 *               `assets/` for a mark.
 * Responsibilities:
 *               - `APP_NAME`, the single spelling of the product name.
 *               - The approved mark and lockup, in both polarities.
 *               - Choosing between them for a given ground colour.
 * Notes:        Lives in `shared/` rather than in a feature because it has no owner:
 *               every screen prints the wordmark and Home, Settings and the play
 *               chrome all need the mark. A feature that owned it would have to be
 *               imported by everything, which is the coupling this migration exists
 *               to remove. Its only dependency is a React Native type, so it is
 *               `shared/` in the strict sense the layer rule means — see
 *               ARCHITECTURE.md §10.
 * Notes:        Two polarities exist because one flat logo cannot work everywhere:
 *               the shipped themes include Paper `#EEEBE4` and Midnight `#0E1120`,
 *               and a single charcoal mark would be invisible on the dark half. The
 *               choice is made from the *ground* the mark sits on, not from the
 *               theme's id, so a new theme picks up the correct logo for free.
 *
 *               The four PNGs under `assets/brand/` are generated by
 *               `npm run icons:brand` from the approved art in
 *               `assets/brand/source/`. Nothing in `assets/brand/` should be
 *               edited by hand: it would be overwritten and the launcher icon
 *               would silently disagree with the in-app mark. This file is *not*
 *               generated — it is the hand-maintained table of what exists, and the
 *               `require()` depths below are relative to this file, so moving it
 *               has to move them with it.
 *
 *               The name is deliberately independent of `app.json`'s `slug`,
 *               `scheme` and package id. Those are install identity: changing them
 *               forks the EAS project and orphans every OTA update already on
 *               players' phones, so they stay as they are while the *display* name
 *               is free to change.
 */

import type { ImageSourcePropType } from 'react-native';

/** The product name, as it appears to a player. */
export const APP_NAME = 'Arrow Puzzle';

/**
 * The approved logo files.
 *
 * `arrowMark` is the glyph alone, for badges and inline marks; `wordmark` is the
 * glyph locked up with the name, for anywhere the game is introduced.
 */
export const BRAND = {
  /** Glyph alone, charcoal ink, for light grounds. */
  arrowMark: require('../../../assets/brand/arrow-mark.png'),
  /** Glyph alone, bone ink, for dark grounds. */
  arrowMarkLight: require('../../../assets/brand/arrow-mark-light.png'),
  /** Mark plus name, charcoal ink, for light grounds. */
  wordmark: require('../../../assets/brand/wordmark.png'),
  /** Mark plus name, bone ink, for dark grounds. */
  wordmarkLight: require('../../../assets/brand/wordmark-light.png'),
} as const;

/**
 * Is a background colour dark enough that an ink mark would disappear on it?
 *
 * Uses relative luminance rather than a lightness average, so the bright yellow
 * `noodles` ground and the near-black `bold` ground land on the correct sides.
 * Anything unparseable is treated as light, which is the safer default: the light
 * ink is a softer failure than an invisible mark.
 *
 * @param color A `#rrggbb` (or `#rgb`) string.
 */
export function isDarkColor(color: string): boolean {
  const hex = color.trim().replace('#', '');
  const full =
    hex.length === 3
      ? `${hex[0] ?? ''}${hex[0] ?? ''}${hex[1] ?? ''}${hex[1] ?? ''}${hex[2] ?? ''}${hex[2] ?? ''}`
      : hex;

  if (full.length !== 6 || !/^[0-9a-f]{6}$/i.test(full)) return false;

  const channel = (offset: number): number => {
    const value = parseInt(full.slice(offset, offset + 2), 16) / 255;
    return value <= 0.04045 ? value / 12.92 : Math.pow((value + 0.055) / 1.055, 2.4);
  };

  const luminance = 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4);
  return luminance < 0.5;
}

/**
 * The glyph for a given ground, as an image source.
 *
 * @param onDarkGround Whether the surface behind the mark is dark.
 */
export function brandMark(onDarkGround: boolean): ImageSourcePropType {
  return onDarkGround ? BRAND.arrowMarkLight : BRAND.arrowMark;
}

/**
 * The full lockup for a given ground, as an image source.
 *
 * @param onDarkGround Whether the surface behind the lockup is dark.
 */
export function brandWordmark(onDarkGround: boolean): ImageSourcePropType {
  return onDarkGround ? BRAND.wordmarkLight : BRAND.wordmark;
}
